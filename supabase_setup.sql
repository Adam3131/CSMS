-- ========================================================
-- SUPABASE DDL SETUP FOR CSMS (Contractor Safety Management System)
-- ========================================================

-- Enable necessary extensions
create extension if not exists "uuid-ossp";

-- --------------------------------------------------------
-- 1. Table: profiles
-- Handles user profile information linked to Supabase Auth
-- --------------------------------------------------------
create table if not exists public.profiles (
    id uuid references auth.users on delete cascade primary key,
    full_name text,
    role text,
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable RLS for profiles
alter table public.profiles enable row level security;

-- Policies for profiles
create policy "Public profiles are viewable by everyone." on public.profiles
    for select using (true);

create policy "Users can insert their own profile." on public.profiles
    for insert with check (auth.uid() = id);

create policy "Users can update their own profile." on public.profiles
    for update using (auth.uid() = id);

-- --------------------------------------------------------
-- 2. Table: documents
-- Core table storing the CSMS documents (HSE Plan, PJA, WIP, FE)
-- Used by src/utils/documentStore.ts
-- --------------------------------------------------------
create table if not exists public.documents (
    no bigint generated by default as identity primary key,
    nama text not null,
    added varchar(50) not null, -- formatted date string like "23-Nov-2025"
    added_date timestamp with time zone default timezone('utc'::text, now()) not null,
    status text not null check (status in ('New', 'On Progress', 'Done', 'On Review', 'Approved', 'Need Revision', 'Draft')),
    type text not null check (type in ('HSE Plan', 'PJA', 'WIP', 'FE')),
    file_name text null,
    file_path text null,
    nilai varchar(50) null -- optional rating/score
);

-- Enable RLS for documents
alter table public.documents enable row level security;

-- Policies for documents (For development, allow public anonymous read/write)
create policy "Allow read access to all users" on public.documents
    for select using (true);

create policy "Allow insert access to all users" on public.documents
    for insert with check (true);

create policy "Allow update access to all users" on public.documents
    for update using (true);

create policy "Allow delete access to all users" on public.documents
    for delete using (true);

