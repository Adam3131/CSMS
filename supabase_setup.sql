-- Table for full HSE Plan details
create table if not exists public.hse_plan_submissions (
    id bigint generated by default as identity primary key,
    document_no bigint references public.documents(no) on delete cascade unique,
    vendor_name text,
    project_name text,
    evaluation_date date,
    evaluator_name text,
    lokasi_pekerjaan text,
    pic_jabatan text,
    matrix_scores jsonb, -- Storing all questionnaire scores in a single JSON structure
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.hse_plan_submissions enable row level security;
create policy "Allow read access to hse_plan_submissions" on public.hse_plan_submissions for select using (true);
create policy "Allow write access to hse_plan_submissions" on public.hse_plan_submissions for all using (true);

-- Table for full Pre-Job Assessment (PJA) details
create table if not exists public.pja_submissions (
    id bigint generated by default as identity primary key,
    document_no bigint references public.documents(no) on delete cascade unique,
    vendor_name text,
    project_name text,
    bidang_usaha text,
    evaluation_date date,
    evaluator_name text,
    pic_jabatan text,
    lokasi_pekerjaan text,
    answers jsonb, -- Storing YES/NO/NO_NEED questionnaires in JSON
    notes jsonb, -- Storing notes for each question
    due_date date,
    keterangan text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.pja_submissions enable row level security;
create policy "Allow read access to pja_submissions" on public.pja_submissions for select using (true);
create policy "Allow write access to pja_submissions" on public.pja_submissions for all using (true);

-- Table for full Work In Progress (WIP) details
create table if not exists public.wip_submissions (
    id bigint generated by default as identity primary key,
    document_no bigint references public.documents(no) on delete cascade unique,
    stage text,
    nama_perusahaan text,
    jenis_pekerjaan text,
    lokasi_pekerjaan text,
    tanggal_penilaian date,
    evaluator text,
    lagging_indicators jsonb, -- JSON with target, actual, sanksi
    leading_indicators jsonb, -- JSON with target, actual, sanksi
    pja_lagging jsonb,
    pja_leading jsonb,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.wip_submissions enable row level security;
create policy "Allow read access to wip_submissions" on public.wip_submissions for select using (true);
create policy "Allow write access to wip_submissions" on public.wip_submissions for all using (true);

